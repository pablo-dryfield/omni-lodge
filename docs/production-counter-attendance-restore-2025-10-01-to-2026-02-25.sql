    AND current.kind::text = restored.kind
    AND current.addon_id IS NOT DISTINCT FROM restored.addon_id
    AND current.period::text IS NOT DISTINCT FROM restored.period
    AND current.tally_type = 'attended'
    AND counter.id = current.counter_id
    AND counter.date BETWEEN DATE '2025-10-01' AND DATE '2026-02-25'
    AND current.qty IS DISTINCT FROM restored.qty
  RETURNING current.id
)
SELECT COUNT(*) AS updated_metrics FROM updated;

