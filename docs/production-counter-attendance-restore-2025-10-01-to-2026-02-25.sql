SELECT
  SUM(CASE WHEN m.tally_type = 'booked' AND m.kind = 'people' THEN m.qty ELSE 0 END)::integer AS booked,
  SUM(CASE WHEN m.tally_type = 'attended' AND m.kind = 'people' THEN m.qty ELSE 0 END)::integer AS attended,
  (SUM(CASE WHEN m.tally_type = 'booked' AND m.kind = 'people' THEN m.qty ELSE 0 END)
   - SUM(CASE WHEN m.tally_type = 'attended' AND m.kind = 'people' THEN m.qty ELSE 0 END))::integer AS no_shows
FROM counter_channel_metrics m
JOIN counters c ON c.id = m.counter_id
WHERE c.date = DATE '2025-10-31';

