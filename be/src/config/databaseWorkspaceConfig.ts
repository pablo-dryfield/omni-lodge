import type { ConfigDefinition } from './appConfigRegistry.js';

const category = 'Database Workspace';
const flag = (
  key: string,
  label: string,
  description: string,
): ConfigDefinition => ({
  key: `DB_WORKSPACE_${key}`,
  label,
  description,
  category,
  valueType: 'boolean',
  defaultValue: false,
  impact: 'high',
});
const limit = (
  key: string,
  label: string,
  value: number,
  min: number,
  max: number,
): ConfigDefinition => ({
  key: `DB_WORKSPACE_${key}`,
  label,
  description:
    'Database Workspace limit. Applies to new jobs and is enforced by the execution worker; lowering a limit never broadens an active operation.',
  category,
  valueType: 'number',
  defaultValue: value,
  validation: { min, max },
  impact: 'high',
});

